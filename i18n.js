let current = DEFAULT_UI_LANGUAGE;

export const TRANSLATED_KEYS = new Set(Object.keys(SV));

export function setUiLanguage(value) {
  current = UI_LANGUAGES.includes(value) ? value : DEFAULT_UI_LANGUAGE;
  if (typeof document !== "undefined" && document.documentElement) document.documentElement.lang = current;
  return current;
}

export function getUiLanguage() {
  return current;
}

/** Översätter en engelsk nyckel och fyller i {platshållare}. */
export function t(key, vars = {}) {
  const text = current === "sv" ? (SV[key] ?? key) : key;
  return String(text).replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

/** Översätter statisk markup: text, HTML, placeholder, title och aria-label. */
export function applyI18n(root = document) {
  for (const element of root.querySelectorAll("[data-i18n]")) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const element of root.querySelectorAll("[data-i18n-html]")) {
    element.innerHTML = t(element.dataset.i18nHtml);
  }
  for (const element of root.querySelectorAll("[data-i18n-placeholder]")) {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  }
  for (const element of root.querySelectorAll("[data-i18n-title]")) {
    element.title = t(element.dataset.i18nTitle);
  }
  for (const element of root.querySelectorAll("[data-i18n-aria]")) {
    element.setAttribute("aria-label", t(element.dataset.i18nAria));
  }
}

/** Läser sparat språk, sätter <html lang> och översätter sidan. */
export function startI18n(settings = {}) {
  setUiLanguage(settings.uiLanguage);
  applyI18n();
}
